func testEnv(t *testing.T) (*Engine, *stcfg.Config) {
	t.Helper()
	dir := t.TempDir()
	e := &Engine{
		ConfigDir:    filepath.Join(dir, "config"),
		ManifestPath: filepath.Join(dir, "stageneth", "manifest.json"),
		RsyslogConf:  filepath.Join(dir, "rsyslog.conf"),
		Avail:        map[string]bool{"eth0": true, "eth1": true, "eth2": true},
	}
	os.MkdirAll(e.ConfigDir, 0755)
	os.WriteFile(filepath.Join(e.ConfigDir, "network"), []byte(existingNetwork), 0644)
	st := stcfg.Parse(ucifile.Parse(stagenethConf))
	return e, st
}

func TestApplyGeneratesAndPreserves(t *testing.T) {
	e, st := testEnv(t)
	changed, _, err := e.Apply(st)
	if err != nil {
		t.Fatal(err)
	}
	if len(changed) == 0 {
		t.Fatal("expected changes on first apply")
	}
	b, _ := os.ReadFile(filepath.Join(e.ConfigDir, "network"))
	net := string(b)
	for _, want := range []string{
		"config interface 'svc_dante'",
		"config device 'br_dante'",
		"config device 'eth1_20'",
		"option vid '20'",
		"config interface 'lan'", // preserved
		"config interface 'wan'", // preserved
		"config interface 'loopback'",
	} {
		if !strings.Contains(net, want) {
			t.Errorf("network missing %q:\n%s", want, net)
		}
	}
	fw, _ := os.ReadFile(filepath.Join(e.ConfigDir, "firewall"))
	for _, want := range []string{
		"config zone 'zone_dante'",
		"config rule 'allow_syslog_dante'",
		"config forwarding 'mgmt_to_dante'",
	} {
		if !strings.Contains(string(fw), want) {
			t.Errorf("firewall missing %q:\n%s", want, fw)
		}
	}
	rs, _ := os.ReadFile(filepath.Join(e.ConfigDir, "rsyslog"))
	if !strings.Contains(string(rs), "config forwarder 'stageneth_remote'") {
		t.Error("rsyslog missing forwarder section")
	}
	if !strings.Contains(string(rs), "option udp_input '1'") {
		t.Error("rsyslog missing collector input")
	}
	rc, _ := os.ReadFile(e.RsyslogConf)
	if !strings.Contains(string(rc), "stagenethRemoteFile") {
		t.Error("rsyslog.conf missing collector block")
	}
}

func TestApplyIdempotent(t *testing.T) {
	e, st := testEnv(t)
	if _, _, err := e.Apply(st); err != nil {
		t.Fatal(err)
	}
	changed, _, err := e.Apply(st)
	if err != nil {
		t.Fatal(err)
	}
	if len(changed) != 0 {
		t.Fatalf("second apply changed %v", changed)
	}
}

func TestStaleSectionsRemoved(t *testing.T) {
	e, st := testEnv(t)
	if _, _, err := e.Apply(st); err != nil {
		t.Fatal(err)
	}
	// Remove the dante service: generated sections must disappear,
	// user sections must survive.
	delete(st.Services, "dante")
	if _, _, err := e.Apply(st); err != nil {
		t.Fatal(err)
	}
	b, _ := os.ReadFile(filepath.Join(e.ConfigDir, "network"))
	net := string(b)
	if strings.Contains(net, "svc_dante") || strings.Contains(net, "br_dante") || strings.Contains(net, "eth1_20") {
		t.Error("stale generated sections not removed:\n" + net)
	}
	if !strings.Contains(net, "config interface 'lan'") {
		t.Error("user section removed")
	}
}

func TestLegacyCleanupWithoutManifest(t *testing.T) {
	e, st := testEnv(t)
	// Simulate sections generated by the pre-stagenethd orchestrator:
	// stale svc_olde service + a user forwarding that must survive.
	extra := `
config interface 'svc_old'
	option device 'br_old'
	option proto 'static'
	option ipaddr '10.99.0.1'
	option netmask '255.255.255.0'

config device 'br_old'
	option name 'br_old'
	option type 'bridge'
	option ports 'eth1.99'
`
	f, _ := os.OpenFile(filepath.Join(e.ConfigDir, "network"), os.O_APPEND|os.O_WRONLY, 0644)
	f.WriteString(extra)
	f.Close()
	if _, _, err := e.Apply(st); err != nil {
		t.Fatal(err)
	}
	b, _ := os.ReadFile(filepath.Join(e.ConfigDir, "network"))
	net := string(b)
	if strings.Contains(net, "svc_old") || strings.Contains(net, "br_old") {
		t.Error("legacy generated sections not cleaned:\n" + net)
	}
	if !strings.Contains(net, "config interface 'wan'") {
		t.Error("user section removed")
	}
}

func TestSnapshotRestore(t *testing.T) {
	e, st := testEnv(t)
	before, _ := os.ReadFile(filepath.Join(e.ConfigDir, "network"))
	_, snap, err := e.Apply(st)
	if err != nil || snap == nil {
		t.Fatalf("apply: %v snap=%v", err, snap)
	}
	// Corrupt a managed file, then restore.
	os.WriteFile(filepath.Join(e.ConfigDir, "network"), []byte("garbage"), 0644)
	if err := e.Restore(snap); err != nil {
		t.Fatal(err)
	}
	after, _ := os.ReadFile(filepath.Join(e.ConfigDir, "network"))
	if string(after) != string(before) {
		t.Error("restore did not revert file contents")
	}
}

func TestLastGoodRollback(t *testing.T) {
	e, st := testEnv(t)
	before, _ := os.ReadFile(filepath.Join(e.ConfigDir, "network"))
	_, snap, err := e.Apply(st)
	if err != nil {
		t.Fatal(err)
	}
	if err := e.SaveLastGood(snap); err != nil {
		t.Fatal(err)
	}
	// corrupt live files, roll back from disk
	os.WriteFile(filepath.Join(e.ConfigDir, "network"), []byte("garbage"), 0644)
	os.WriteFile(filepath.Join(e.ConfigDir, "firewall"), []byte("garbage"), 0644)
	restored, err := e.Rollback()
	if err != nil {
		t.Fatal(err)
	}
	if len(restored) == 0 {
		t.Fatal("nothing restored")
	}
	after, _ := os.ReadFile(filepath.Join(e.ConfigDir, "network"))
	if string(after) != string(before) {
		t.Error("rollback did not restore pre-apply content")
	}
	// firewall didn't exist at snapshot time → rollback removes it
	if _, err := os.Stat(filepath.Join(e.ConfigDir, "firewall")); !os.IsNotExist(err) {
		t.Error("rollback should remove apply-created files")
	}
}

func TestRollbackNoSnapshot(t *testing.T) {
	e, _ := testEnv(t)
	if _, err := e.Rollback(); err == nil {
		t.Error("rollback without snapshot should fail")
	}
}

func TestPreviewDoesNotWrite(t *testing.T) {
	e, st := testEnv(t)
	plan, err := e.Plan(st)
	if err != nil {
		t.Fatal(err)
	}
	var addFound, anyChanged bool
	for _, fc := range plan.Changes {
		if fc.Changed {
			anyChanged = true
		}
		for _, a := range fc.Added {
			if a == "svc_dante" {
				addFound = true
			}
		}
	}
	if !anyChanged || !addFound {
		t.Fatal("plan missing expected changes")
	}
	if _, err := os.Stat(filepath.Join(e.ConfigDir, "firewall")); !os.IsNotExist(err) {
		t.Error("preview wrote files")
	}
}
